from dataclasses import dataclass, field

from trading.decision.trading_action import TradingAction


@dataclass(slots=True)
class DecisionResult:
    """
    Final decision generated by the AI engine.
    """

    action: TradingAction = TradingAction.HOLD

    confidence: float = 0.0

    bullish_score: float = 0.0

    bearish_score: float = 0.0

    probability: float = 0.0

    explanation: list[str] = field(
        default_factory=list
    )

    def is_buy(self) -> bool:

        return self.action == TradingAction.BUY

    def is_sell(self) -> bool:

        return self.action == TradingAction.SELL

    def is_hold(self) -> bool:

        return self.action == TradingAction.HOLD

    def is_exit(self) -> bool:

        return self.action == TradingAction.EXIT

    def is_wait(self) -> bool:

        return self.action == TradingAction.WAIT
